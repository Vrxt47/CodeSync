import type { ExecutionAdapter } from "../execution.interface";
import type { ExecutionRequest, ExecutionResult, SupportedLanguage } from "../execution.types";

/**
 * Isolated mock execution adapter for CodeSync.
 *
 * SAFETY INVARIANTS:
 * - NEVER uses eval() or new Function().
 * - NEVER executes shell commands or child processes.
 * - Deterministically simulates compiler and runtime behaviors.
 * - Explicitly marks all returned metrics and output as simulated.
 */
export class MockExecutionAdapter implements ExecutionAdapter {
  public readonly name = "MockExecutionAdapter";

  /**
   * @param delayMs Simulated execution latency in milliseconds (default: 500ms).
   */
  constructor(private readonly delayMs: number = 500) {}

  public async execute(request: ExecutionRequest): Promise<ExecutionResult> {
    // 1. Simulate async sandbox execution delay
    if (this.delayMs > 0) {
      await new Promise((resolve) => setTimeout(resolve, this.delayMs));
    }

    const { sourceCode, language, stdin } = request;
    const executionId = `mock-exec-${Date.now()}-${Math.random().toString(36).substring(2, 8)}`;
    const executedAt = new Date().toISOString();

    // 2. Scenario: Empty source code -> Validation Error
    if (!sourceCode || sourceCode.trim().length === 0) {
      return {
        executionId,
        status: "validation_error",
        stdout: "",
        stderr: "",
        validationError: "Source code cannot be empty. Please enter code to execute.",
        executionTime: 0,
        memoryUsage: 0,
        exitCode: 1,
        executedAt,
        isSimulated: true,
      };
    }

    // 3. Scenario: Mock Compilation Error trigger
    if (sourceCode.includes("MOCK_COMPILE_ERROR")) {
      return this.handleCompilationError(executionId, language, executedAt);
    }

    // 4. Scenario: Mock Runtime Error trigger
    if (sourceCode.includes("MOCK_RUNTIME_ERROR")) {
      return this.handleRuntimeError(executionId, language, executedAt);
    }

    // 5. Scenario: Mock Standard Error trigger
    if (sourceCode.includes("MOCK_STDERR")) {
      return {
        executionId,
        status: "success",
        stdout:
          "[Standard Output] Process initialized and executed successfully.\n[Info] Output generated by simulated runner.",
        stderr:
          "[Standard Error - Warning] Resource handle closed implicitly.\n[Warning] Deprecated function invocation at line 4.",
        executionTime: this.getSimulatedTime(language),
        memoryUsage: this.getSimulatedMemory(language),
        exitCode: 0,
        executedAt,
        isSimulated: true,
      };
    }

    // 6. Scenario: Mock Stdin Echo trigger
    if (sourceCode.includes("MOCK_ECHO_STDIN")) {
      const hasStdin = stdin && stdin.trim().length > 0;
      const echoOutput = hasStdin
        ? `[Standard Input Received]:\n${stdin}`
        : "[Standard Input Received]:\n<No standard input provided>";

      return {
        executionId,
        status: "success",
        stdout: echoOutput,
        stderr: "",
        executionTime: this.getSimulatedTime(language),
        memoryUsage: this.getSimulatedMemory(language),
        exitCode: 0,
        executedAt,
        isSimulated: true,
      };
    }

    // 7. Scenario: Default successful execution per language
    return this.handleSuccess(executionId, language, sourceCode, executedAt);
  }

  private handleCompilationError(
    executionId: string,
    language: SupportedLanguage,
    executedAt: string
  ): ExecutionResult {
    let compilationError: string;

    switch (language) {
      case "cpp":
        compilationError =
          "main.cpp: In function 'int main()':\n" +
          "main.cpp:5:5: error: 'cout' was not declared in this scope; did you mean 'std::cout'?\n" +
          '    5 |     cout << "Hello, CodeSync!" << endl;\n' +
          "      |     ^~~~\n" +
          "      |     std::cout\n" +
          "main.cpp:5:35: error: 'endl' was not declared in this scope; did you mean 'std::endl'?\n" +
          '    5 |     cout << "Hello, CodeSync!" << endl;\n' +
          "      |                                   ^~~~\n" +
          "      |                                   std::endl";
        break;

      case "java":
        compilationError =
          "Main.java:3: error: cannot find symbol\n" +
          '        System.out.printl("Hello, CodeSync!");\n' +
          "                  ^\n" +
          "  symbol:   method printl(String)\n" +
          "  location: variable out of type PrintStream\n" +
          "1 error";
        break;

      case "python":
        compilationError =
          '  File "main.py", line 2\n' +
          '    print("Hello, CodeSync!"\n' +
          "                            ^\n" +
          "SyntaxError: '(' was never closed";
        break;

      case "javascript":
      default:
        compilationError =
          "SyntaxError: Unexpected token ')'\n" +
          "    at new Script (node:vm:100:7)\n" +
          "    at createScript (node:vm:257:10)";
        break;
    }

    return {
      executionId,
      status: "compilation_error",
      stdout: "",
      stderr: "",
      compilationError,
      executionTime: 12,
      memoryUsage: 2.1,
      exitCode: 1,
      executedAt,
      isSimulated: true,
    };
  }

  private handleRuntimeError(
    executionId: string,
    language: SupportedLanguage,
    executedAt: string
  ): ExecutionResult {
    let runtimeError: string;
    let exitCode = 1;

    switch (language) {
      case "python":
        runtimeError =
          "Traceback (most recent call last):\n" +
          '  File "main.py", line 4, in <module>\n' +
          "    divide(10, 0)\n" +
          '  File "main.py", line 2, in divide\n' +
          "    return a / b\n" +
          "ZeroDivisionError: division by zero";
        break;

      case "javascript":
        runtimeError =
          "ReferenceError: myUndefinedVariable is not defined\n" +
          "    at calculateTotal (index.js:4:5)\n" +
          "    at Object.<anonymous> (index.js:8:1)\n" +
          "    at Module._compile (node:internal/modules/cjs/loader:1256:14)";
        break;

      case "cpp":
        runtimeError =
          "terminate called after throwing an instance of 'std::out_of_range'\n" +
          "  what():  vector::_M_range_check: __n (which is 10) >= this->size() (which is 3)\n" +
          "Aborted (core dumped)";
        exitCode = 139; // SIGSEGV/SIGABRT exit code
        break;

      case "java":
      default:
        runtimeError =
          'Exception in thread "main" java.lang.ArithmeticException: / by zero\n' +
          "\tat Main.divide(Main.java:6)\n" +
          "\tat Main.main(Main.java:2)";
        break;
    }

    return {
      executionId,
      status: "runtime_error",
      stdout: "",
      stderr: "",
      runtimeError,
      executionTime: this.getSimulatedTime(language),
      memoryUsage: this.getSimulatedMemory(language),
      exitCode,
      executedAt,
      isSimulated: true,
    };
  }

  private handleSuccess(
    executionId: string,
    language: SupportedLanguage,
    sourceCode: string,
    executedAt: string
  ): ExecutionResult {
    let stdout: string;

    // Provide friendly simulated output reflecting the language default
    switch (language) {
      case "python":
        stdout = sourceCode.includes('print("Hello, CodeSync!")')
          ? "Hello, CodeSync!\n"
          : "Hello, CodeSync!\n[Process exited with return code 0]";
        break;

      case "cpp":
        stdout = sourceCode.includes('std::cout << "Hello, CodeSync!"')
          ? "Hello, CodeSync!\n"
          : "Hello, CodeSync!\n[Process exited with return code 0]";
        break;

      case "java":
        stdout = sourceCode.includes('System.out.println("Hello, CodeSync!");')
          ? "Hello, CodeSync!\n"
          : "Hello, CodeSync!\n[Process exited with return code 0]";
        break;

      case "javascript":
      default:
        stdout = sourceCode.includes('console.log("Hello, CodeSync!");')
          ? "Hello, CodeSync!\n"
          : "Hello, CodeSync!\n[Process exited with return code 0]";
        break;
    }

    return {
      executionId,
      status: "success",
      stdout,
      stderr: "",
      executionTime: this.getSimulatedTime(language),
      memoryUsage: this.getSimulatedMemory(language),
      exitCode: 0,
      executedAt,
      isSimulated: true,
    };
  }

  private getSimulatedTime(language: SupportedLanguage): number {
    switch (language) {
      case "cpp":
        return 16;
      case "python":
        return 38;
      case "javascript":
        return 44;
      case "java":
        return 118;
      default:
        return 50;
    }
  }

  private getSimulatedMemory(language: SupportedLanguage): number {
    switch (language) {
      case "cpp":
        return 3.8;
      case "python":
        return 11.4;
      case "javascript":
        return 14.6;
      case "java":
        return 27.2;
      default:
        return 10.0;
    }
  }
}
